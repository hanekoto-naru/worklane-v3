import { test, expect, modal, saved } from './fixtures.mjs'

test('日付欄全体で開く月曜始まりのカレンダーをキーボードで操作し、日付を保持する', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2030-04-15T12:00:00Z'))
  await page.goto('/#/mine')
  await page.getByRole('button', { name: '新規登録', exact: true }).click()
  await modal(page).getByLabel('タイトル（必須）').fill('日付選択の検証')
  const due = modal(page).locator('input[name="due"]')
  await due.click({ position: { x: 15, y: 15 } })
  const calendar = page.getByRole('dialog', { name: '期限を選択', exact: true })
  await expect(calendar).toBeVisible()
  await expect(calendar.locator('div[aria-hidden="true"] > span')).toHaveText(['月', '火', '水', '木', '金', '土', '日'])
  await expect(calendar.getByRole('button', { name: '2030/4/14（日）', exact: true })).toBeDisabled()
  await expect(calendar.getByRole('button', { name: '前の月', exact: true })).toBeDisabled()
  await expect(calendar.getByRole('button', { name: '2030/4/15（月）', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(calendar.getByRole('button', { name: '2030/4/16（火）', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(calendar).toHaveCount(0)
  await expect(due).toBeFocused()
  await expect(due).toHaveValue('2030-04-16')
  await page.keyboard.press('Alt+ArrowDown')
  await page.keyboard.press('PageDown')
  await expect(calendar.getByRole('button', { name: '2030/5/1（水）', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(due).toBeFocused()
  await expect(due).toHaveValue('2030-04-16')
  await due.fill('2030-04-14')
  await expect(due).toHaveValue('2030-04-16')
  await modal(page).getByRole('button', { name: '登録', exact: true }).click()
  await page.getByRole('button', { name: '日付選択の検証', exact: true }).click()
  await expect(modal(page).locator('input[name="due"]')).toHaveValue('2030-04-16')
})

test('既存の過去の期限を保ったままタイトルを変更できる', async ({ page, disk }) => {
  disk.files.set('dummy-a/data.json', JSON.stringify({ schemaVersion: 1, revision: 1, people: [], projects: [], questions: [], tasks: [
    { id: 'past', kind: 'mine', title: '期限超過の検証', detail: '', status: '未着手', priority: 'なし', due: '2020-01-01', project: '', owner: '自分', url: '' },
  ] }))
  await page.goto('/#/mine')
  await page.getByRole('button', { name: '保存先フォルダを選択', exact: true }).click()
  await saved(page)
  await page.getByRole('button', { name: '期限超過の検証', exact: true }).click()
  await modal(page).getByLabel('タイトル（必須）').fill('期限超過の検証・変更')
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await saved(page)
  const task = JSON.parse(disk.files.get('dummy-a/data.json')).tasks[0]
  expect(task.title).toBe('期限超過の検証・変更')
  expect(task.due).toBe('2020-01-01')
})
