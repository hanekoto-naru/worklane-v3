import { test, expect, modal, nav, confirm, saved, selectEmpty, createTask, storage } from './fixtures.mjs'

const read = disk => JSON.parse(disk.files.get('dummy-a/data.json'))

test('任意の関係者ラベル・並び順・複数ラベル・親子関係・色を保存して再読込する', async ({ page, disk }) => {
  await page.goto('/')
  await selectEmpty(page)
  await nav(page, '設定')
  await page.getByRole('button', { name: '関係者を追加', exact: true }).click()
  await modal(page).getByLabel('名前（必須）').fill('検証担当A')
  await modal(page).getByLabel('新しい関係者ラベル', { exact: true }).fill('品質管理')
  await modal(page).getByRole('button', { name: 'ラベルを追加', exact: true }).click()
  await confirm(page, () => modal(page).getByRole('button', { name: '登録', exact: true }).click(), /保存形式/)
  await saved(page)
  expect(read(disk).schemaVersion).toBe(4)
  await expect(page.getByRole('row').filter({ hasText: '検証担当A' })).toContainText('品質管理')
  await page.getByRole('button', { name: '関係者を追加', exact: true }).click()
  await modal(page).getByLabel('名前（必須）').fill('検証担当B')
  await modal(page).getByRole('button', { name: '品質管理', exact: true }).click()
  await modal(page).getByRole('button', { name: '登録', exact: true }).click()
  await saved(page)
  await page.getByRole('button', { name: '検証担当Bを上へ', exact: true }).click()
  await saved(page)
  expect(read(disk).people.map(p => p.name)).toEqual(['検証担当B', '検証担当A'])

  await page.getByRole('group', { name: '設定項目', exact: true }).getByRole('button', { name: 'ラベル', exact: true }).click()
  for (const [name, color] of [['検証親', '青'], ['検証子', '緑']]) {
    await page.getByRole('button', { name: 'ラベルを追加', exact: true }).click()
    await modal(page).getByLabel('ラベル名（必須）').fill(name)
    await modal(page).getByRole('group', { name: 'ラベルの色', exact: true }).getByRole('button', { name: color, exact: true }).click()
    if (name === '検証子') await modal(page).getByRole('group', { name: '親ラベル', exact: true }).getByRole('button', { name: '検証親', exact: true }).click()
    await modal(page).getByRole('button', { name: '登録', exact: true }).click()
    await saved(page)
  }
  const child = read(disk).projects.find(p => p.name === '検証子')
  const parent = read(disk).projects.find(p => p.name === '検証親')
  expect(child.parentId).toBe(parent.id)
  expect(child.color).toBe('green')
  await page.getByRole('button', { name: '検証子を上へ', exact: true }).click()
  await saved(page)
  expect(read(disk).projects.map(p => p.name)).toEqual(['検証子', '検証親'])
  await page.getByRole('button', { name: '検証親を編集', exact: true }).click()
  await modal(page).getByRole('group', { name: '親ラベル', exact: true }).getByRole('button', { name: '検証親 / 検証子', exact: true }).click()
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await expect(modal(page).getByRole('alert')).toContainText('循環')
  await confirm(page, () => modal(page).getByRole('button', { name: 'キャンセル', exact: true }).click(), /破棄/)
  expect(read(disk).projects.find(p => p.id === parent.id).parentId).toBeUndefined()

  await nav(page, '自分のタスク')
  await page.getByRole('button', { name: '新規登録', exact: true }).click()
  await modal(page).getByLabel('タイトル（必須）').fill('複数ラベルの検証')
  const labels = modal(page).getByRole('group', { name: 'ラベル（複数選択）', exact: true })
  await labels.getByRole('button', { name: '検証親', exact: true }).click()
  await labels.getByRole('button', { name: '検証親 / 検証子', exact: true }).click()
  await modal(page).getByRole('group', { name: '関係者（複数選択）', exact: true }).getByRole('button', { name: '検証担当A', exact: true }).click()
  await modal(page).getByRole('button', { name: '登録', exact: true }).click()
  await saved(page)
  expect(read(disk).tasks[0].projects).toEqual([parent.id, child.id])
  expect(read(disk).tasks[0].relatedPeople).toEqual([read(disk).people.find(p => p.name === '検証担当A').id])
  const row = page.getByRole('row').filter({ hasText: '複数ラベルの検証' })
  await expect(row.locator('td').nth(0)).toContainText('未着手')
  await expect(row.locator('td').nth(1).locator('[data-label-color="green"]')).toHaveText('検証親 / 検証子')
  await page.reload()
  await page.getByRole('button', { name: '保存先フォルダを選択', exact: true }).click()
  await saved(page)
  await page.getByRole('button', { name: '複数ラベルの検証', exact: true }).click()
  await expect(modal(page).getByRole('group', { name: 'ラベル（複数選択）', exact: true }).getByRole('button', { pressed: true })).toHaveCount(2)
  await expect(modal(page).getByRole('group', { name: '関係者（複数選択）', exact: true }).getByRole('button', { name: '検証担当A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await modal(page).getByRole('button', { name: 'キャンセル', exact: true }).click()
  await nav(page, '設定')
  await expect(page.locator('tbody tr').first()).toContainText('検証担当B')
  await page.getByRole('group', { name: '設定項目', exact: true }).getByRole('button', { name: 'ラベル', exact: true }).click()
  await expect(page.locator('tbody tr').first()).toContainText('検証親 / 検証子')
})

test('保存済み表示は消え、保存失敗は消えずに残る', async ({ page, disk }) => {
  await page.clock.install()
  await page.goto('/')
  await selectEmpty(page)
  await createTask(page, 'バックアップ一覧の検証')
  await saved(page)
  await page.clock.fastForward(3500)
  await expect(storage(page).getByRole('status')).toHaveCount(0)
  disk.failList = true
  await page.getByRole('button', { name: 'バックアップ', exact: true }).click()
  await expect(storage(page).getByRole('alert')).toContainText('ファイル操作に失敗')
  disk.failList = false
  await page.getByRole('button', { name: '一覧を更新', exact: true }).click()
  await expect(storage(page).getByRole('alert')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '保存先を再選択', exact: true })).toBeVisible()
  disk.failWrite = true
  await createTask(page, '通知の検証')
  await expect(storage(page).getByRole('status')).toHaveText('保存失敗')
  await page.clock.fastForward(3500)
  await expect(storage(page).getByRole('status')).toHaveText('保存失敗')
})

test('旧確認事項をキャンセルで保持し、確認後に内容を保ってタスクへ移行する', async ({ page, disk }) => {
  const original = JSON.stringify({ schemaVersion: 1, revision: 1, tasks: [], projects: [], people: [{ id: 'p', name: '移行担当' }], questions: [
    { id: 'n1', title: '未確認の項目', detail: '引き継ぐ詳細', person: 'p', project: '', checked: false },
    { id: 'n2', title: '確認済みの項目', detail: '', person: 'p', project: '', checked: true },
  ] })
  disk.files.set('dummy-a/data.json', original)
  await page.goto('/#/notes')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('自分のタスク')
  await page.getByRole('button', { name: '保存先フォルダを選択', exact: true }).click()
  await saved(page)
  await expect(page.getByRole('navigation').getByRole('button', { name: '確認事項', exact: true })).toHaveCount(0)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '確認事項をタスクに移行', exact: true }).click()
  expect(disk.files.get('dummy-a/data.json')).toBe(original)
  await confirm(page, () => page.getByRole('button', { name: '確認事項をタスクに移行', exact: true }).click(), /保存形式/)
  await saved(page)
  expect(read(disk).questions).toEqual([])
  expect(read(disk).tasks.map(t => [t.id, t.status, t.relatedPeople])).toEqual([['n1', '未着手', ['p']], ['n2', '完了', ['p']]])
  expect([...disk.files].some(([path, text]) => path.startsWith('dummy-a/backups/') && text === original)).toBe(true)
  await page.getByRole('button', { name: '未確認の項目', exact: true }).click()
  await expect(modal(page).getByLabel('詳細説明')).toHaveValue('引き継ぐ詳細')
  await expect(modal(page).getByRole('group', { name: '関係者（複数選択）', exact: true }).getByRole('button', { name: '移行担当', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('タスクの列幅は長い内容に変更しても動かない', async ({ page }) => {
  await page.goto('/#/mine')
  await createTask(page, '短いタスク')
  const widths = () => page.locator('thead th').evaluateAll(cells => cells.map(cell => cell.getBoundingClientRect().width))
  const before = await widths()
  await page.getByRole('button', { name: '短いタスク', exact: true }).click()
  const longTitle = '長いタスク名の表示検証'.repeat(15)
  await modal(page).getByLabel('タイトル（必須）').fill(longTitle)
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  expect(await widths()).toEqual(before)
  await expect(page.getByRole('button', { name: longTitle, exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1640, height: 1000 })
  const after = await widths()
  before.forEach((width, index) => index === 1 ? expect(after[index]).toBeGreaterThan(width) : expect(after[index]).toBeCloseTo(width, 0))
  const heading = await page.getByRole('heading', { level: 1 }).locator('../..').boundingBox()
  expect(heading.height).toBeLessThan(50)
})

test('関係者ラベルが多い場合は検索ダイアログで複数選択できる', async ({ page, disk }) => {
  disk.files.set('dummy-a/data.json', JSON.stringify({ schemaVersion: 4, revision: 1, tasks: [], projects: [], questions: [],
    people: Array.from({ length: 9 }, (_, i) => ({ id: `p${i}`, name: `担当${i}`, labels: [`分類${i}`] })),
  }))
  await page.goto('/#/settings')
  await page.getByRole('button', { name: '保存先フォルダを選択', exact: true }).click()
  await saved(page)
  await page.getByRole('button', { name: '担当0を編集', exact: true }).click()
  const trigger = modal(page).getByRole('button', { name: '候補を検索・選択（1件）', exact: true })
  await trigger.click()
  const choices = page.getByRole('dialog', { name: '関係者ラベル（複数選択）', exact: true })
  await choices.getByLabel('候補を検索', { exact: true }).fill('分類8')
  await expect(choices.getByRole('group').getByRole('button')).toHaveCount(1)
  await choices.getByRole('button', { name: '分類8', exact: true }).click()
  await choices.getByRole('button', { name: '選択を完了', exact: true }).click()
  await expect(modal(page).getByRole('button', { name: '候補を検索・選択（2件）', exact: true })).toBeFocused()
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await saved(page)
  expect(read(disk).people[0].labels).toEqual(['分類0', '分類8'])
})

test('ラベルと設定の一覧は名前列だけが画面幅に合わせて伸びる', async ({ page }) => {
  const widths = () => page.locator('thead th').evaluateAll(cells => cells.map(cell => cell.getBoundingClientRect().width))
  for (const target of ['labels', 'people', 'settings-labels']) {
    await page.goto(target === 'labels' ? '/#/projects' : '/#/settings')
    if (target === 'settings-labels') await page.getByRole('group', { name: '設定項目', exact: true }).getByRole('button', { name: 'ラベル', exact: true }).click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    const before = await widths()
    await page.setViewportSize({ width: 1640, height: 1000 })
    const after = await widths()
    expect(before.length).toBeGreaterThan(2)
    before.forEach((width, index) => index === 0 ? expect(after[index]).toBeGreaterThan(width) : expect(after[index]).toBeCloseTo(width, 0))
  }
})
