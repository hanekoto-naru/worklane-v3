import { test, expect, modal, nav, confirm, createTask } from './fixtures.mjs'

test('実Chrome: 全画面、関係者・ラベル・依頼の登録編集', async ({ page }) => {
  await page.goto('/')
  for (const name of ['ダッシュボード', '自分のタスク', '依頼したタスク', 'ラベル', '設定']) await nav(page, name)
  await page.getByRole('button', { name: '関係者を追加', exact: true }).click()
  await modal(page).getByLabel('名前（必須）').fill('検証担当者')
  await modal(page).getByRole('button', { name: '営業', exact: true }).click()
  await confirm(page, () => modal(page).getByRole('button', { name: '登録', exact: true }).click(), /保存形式/)
  await page.getByRole('button', { name: '検証担当者を編集', exact: true }).click()
  await modal(page).getByLabel('名前（必須）').fill('検証担当者・変更')
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '検証担当者・変更' })).toContainText('営業')
  await page.getByRole('group', { name: 'ラベルで絞り込み' }).getByRole('button', { name: 'チーム外', exact: true }).click()
  await expect(page.getByRole('button', { name: '検証担当者・変更を編集' })).toHaveCount(0)
  await page.getByRole('group', { name: 'ラベルで絞り込み' }).getByRole('button', { name: '営業', exact: true }).click()
  await expect(page.getByRole('button', { name: '検証担当者・変更を編集' })).toBeVisible()

  await nav(page, 'ラベル')
  await page.getByRole('button', { name: '新規登録', exact: true }).click()
  await modal(page).getByLabel('ラベル名（必須）').fill('検証目標')
  await modal(page).getByRole('button', { name: '登録', exact: true }).click()
  await page.getByRole('row').filter({ has: page.getByRole('button', { name: '検証目標', exact: true }) }).getByRole('button', { name: '編集', exact: true }).click()
  await modal(page).getByLabel('ラベル名（必須）').fill('検証目標・変更')
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await expect(page.getByRole('table').getByRole('button', { name: '検証目標・変更', exact: true })).toBeVisible()

  for (const [name, title] of [['依頼したタスク', '検証依頼']]) {
    await nav(page, name)
    await page.getByRole('button', { name: '新規登録', exact: true }).click()
    await modal(page).getByLabel('タイトル（必須）').fill(title)
    await modal(page).getByRole('group', { name: '登録済みの相手' }).getByRole('button', { name: '検証担当者・変更', exact: true }).click()
    await modal(page).getByRole('group', { name: 'ラベル（複数選択）', exact: true }).getByRole('button', { name: '検証目標・変更', exact: true }).click()
    await modal(page).getByRole('button', { name: '登録', exact: true }).click()
    await page.getByRole('button', { name: title, exact: true }).click()
    await modal(page).getByLabel('タイトル（必須）').fill(title + '・変更')
    await modal(page).getByRole('group', { name: 'ステータス' }).getByRole('button', { name: 'レビュー待ち' }).click()
    await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
    const record = page.getByRole('row').filter({ hasText: title + '・変更' })
    await expect(record).toContainText('検証担当者・変更')
    await expect(record).toContainText('レビュー待ち')
  }
})

test('実Chrome: タスクCRUD、検索・絞り込み、URL拒否、XSS安全表示、モーダル保持', async ({ page }) => {
  await page.goto('/#/mine')
  await expect(page.getByRole('heading', { name: '自分のタスク', level: 1 })).toBeVisible()
  await page.getByRole('button', { name: '新規登録', exact: true }).click()
  await page.mouse.click(5, 5)
  await expect(modal(page)).toHaveCount(0)
  await page.getByRole('button', { name: '新規登録', exact: true }).click()
  const title = '<img src="https://example.invalid/x" onerror="alert(1)">検証'
  await modal(page).getByLabel('タイトル（必須）').fill(title)
  await page.mouse.click(5, 5)
  await expect(modal(page).getByLabel('タイトル（必須）')).toHaveValue(title)
  await modal(page).getByLabel('URL 1', { exact: true }).fill('javascript:alert(1)')
  await modal(page).getByRole('button', { name: '登録', exact: true }).click()
  await expect(modal(page).getByRole('alert')).toContainText('関連URL')
  await modal(page).getByLabel('URL 1', { exact: true }).fill('https://example.invalid/dummy')
  await modal(page).getByRole('button', { name: 'URLを追加', exact: true }).click()
  await modal(page).getByLabel('URL 2', { exact: true }).fill('https://example.invalid/second')
  await confirm(page, () => modal(page).getByRole('button', { name: '登録', exact: true }).click(), /保存形式/)
  await expect(page.getByRole('button', { name: title, exact: true })).toBeVisible()
  await expect(page.locator('img')).toHaveCount(0)
  await page.getByRole('button', { name: title, exact: true }).click()
  await expect(modal(page).getByLabel('URL 2', { exact: true })).toHaveValue('https://example.invalid/second')
  await expect(modal(page).locator('a')).toHaveCount(0)
  await modal(page).getByLabel('タイトル（必須）').fill('検証タスク・変更')
  await modal(page).getByRole('group', { name: 'ステータス' }).getByRole('button', { name: '保留', exact: true }).click()
  await modal(page).getByRole('button', { name: '変更を反映', exact: true }).click()
  await page.getByLabel('一覧を検索').fill('検証タスク・変更')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByRole('group', { name: '状態で絞り込み' })).toHaveCount(0)
  await expect(page.locator('tbody tr')).toContainText('保留')
  await page.getByRole('button', { name: '検証タスク・変更', exact: true }).click()
  await confirm(page, () => modal(page).getByRole('button', { name: '削除', exact: true }).click(), /削除/)
  await expect(page.getByRole('button', { name: '検証タスク・変更', exact: true })).toHaveCount(0)
})

test('実Chrome: 未保存モーダルで離脱すると警告し、キャンセルで入力を維持', async ({ page }) => {
  await page.goto('/#/mine')
  await createTask(page, '離脱テスト')
  await page.getByRole('button', { name: '離脱テスト', exact: true }).click()
  await modal(page).getByLabel('タイトル（必須）').fill('入力保持')
  const event = page.waitForEvent('dialog')
  await page.evaluate(() => { setTimeout(() => window.location.reload(), 0) })
  const dialog = await event
  expect(dialog.type()).toBe('beforeunload')
  await dialog.dismiss()
  await expect(modal(page).getByLabel('タイトル（必須）')).toHaveValue('入力保持')
})


